describe("questions", () => {
  it("submits a numeric answer and only then shows the correct answer", async () => {
    const onSubmit = vi.fn();
    const { rerender } = render(<QuestionView question={numericQuestion} onSubmit={onSubmit} submitting={false} locked={false} />);
    expect(screen.queryByText(/correct answer/i)).not.toBeInTheDocument();
    await userEvent.type(screen.getByLabelText("Your answer"), "4500");
    await userEvent.click(screen.getByRole("button", { name: /submit answer/i }));
    expect(onSubmit).toHaveBeenCalledWith({ item_id: 448752, value: "4500" });
    rerender(
      <QuestionView
        question={numericQuestion}
        onSubmit={onSubmit}
        submitting={false}
        locked
        feedback={{ correct: false, correct_answer: { type: "numeric", values: ["4500"] }, message: "Not quite." }}
      />,
    );
    expect(screen.getByText("Not quite.")).toBeInTheDocument();
    expect(screen.getByText("4500")).toBeInTheDocument();
    expect(screen.queryByRole("button", { name: /submit answer/i })).not.toBeInTheDocument();
  });

  it("accepts typed algebra answers and shows the accepted forms afterwards", async () => {
    const onSubmit = vi.fn();
    const q = { ...numericQuestion, answer_type: "algebraic" as const, input_hint: "e.g. 3x+2, 2(x-1), x^2, 5/2x, sqrt(7) or 36pi" };
    const { rerender } = render(<QuestionView question={q} onSubmit={onSubmit} submitting={false} locked={false} />);
    const box = screen.getByLabelText("Your answer");
    expect(box).toHaveAttribute("placeholder", q.input_hint);
    expect(screen.getByText(/Type powers as x\^2/)).toBeInTheDocument();
    await userEvent.type(box, "2(13a-5)");
    await userEvent.click(screen.getByRole("button", { name: /submit answer/i }));
    expect(onSubmit).toHaveBeenCalledWith({ item_id: 448752, value: "2(13a-5)" });
    rerender(<QuestionView question={q} onSubmit={onSubmit} submitting={false} locked feedback={{ correct: false, correct_answer: { type: "text", values: ["2(13a-5)"] }, message: "Not quite." }} />);
    expect(screen.getByText("2(13a-5)")).toBeInTheDocument();
  });
});

describe("practice", () => {
  const wrongAnswer = {
    interaction_id: 77,
    correct: false,
    hint_used: true,
    revealed: false,
    correct_answer: { type: "multiple_choice", option_ids: ["2"], options_html: ["About 2,700 in²"] },
    message: "Not quite. Let's look at it again.",
    difficulty_before: "medium",
    difficulty_next: "medium",
    difficulty_change: null,
    answered: 2,
    total: 8,
    complete: false,
    summary: null,
    early_stop: null,
  };

  it("has one Hint button; the AI hint is inside it and can be retried after a fallback", async () => {
    let aiCalls = 0;
    const calls = mockApi({
      ...base,
      ...aiOn,
      "GET /api/v2/practice/p2/next": { body: choiceQuestion },
      "POST /api/v2/practice/p2/hint": (_b, url) => {
        if (url.searchParams.get("ai") !== "true") return { body: { kind: "concept", text: "Area = πr².", source: "Circles" } };
        aiCalls += 1;
        return aiCalls === 1
          ? { body: { kind: "concept", text: "Area = πr².", source: "Circles", ai_failed: true, note: "The AI tutor couldn't give a specific hint this time." } }
          : { body: { kind: "ai", text: "Compare the radii first.", source: "AI tutor", label: "AI-generated by a free language model.", ai_failed: false } };
      },
    });
    renderAt("/practice/p2");
    expect(await screen.findByText("Which could be the area of circle B?")).toBeInTheDocument();
    expect(screen.queryByRole("button", { name: /ai hint/i })).not.toBeInTheDocument();
    await userEvent.click(screen.getByRole("button", { name: /^hint$/i }));
    expect(await screen.findByText("Area = πr².")).toBeInTheDocument();
    await userEvent.click(await screen.findByRole("button", { name: /ask the ai tutor for a more specific hint/i }));
    expect(await screen.findByText(/couldn't give a specific hint this time/)).toBeInTheDocument();
    await userEvent.click(screen.getByRole("button", { name: /try the ai hint again/i }));
    expect(await screen.findByText("Compare the radii first.")).toBeInTheDocument();
    expect(screen.getByText(/AI-generated by a free language model/)).toBeInTheDocument();
    expect(calls.filter((c) => c.path === "/api/v2/practice/p2/hint")).toHaveLength(3);
  });

  it("shows the server's AI error with Try again, then the explanation", async () => {
    let n = 0;
    mockApi({
      ...base,
      ...aiOn,
      "GET /api/v2/practice/p2/next": { body: choiceQuestion },
      "POST /api/v2/practice/p2/answer": { body: wrongAnswer },
      "POST /api/v2/ai/explain": () =>
        n++ === 0
          ? { status: 503, body: { error: { code: "ai_unavailable", message: "The AI tutor is busy right now. Please try again in a minute." } } }
          : { body: { kind: "explanation", content: "1. The radius triples.\n2. Area grows 9 times.", model: "test-model", cached: false, label: "AI-generated by a free language model." } },
    });
    renderAt("/practice/p2");
    await userEvent.click(await screen.findByText("About 100 in²"));
    await userEvent.click(screen.getByRole("button", { name: /submit answer/i }));
    await userEvent.click(await screen.findByRole("button", { name: /explain my mistake with ai/i }));
    expect(await screen.findByText("The AI tutor is busy right now. Please try again in a minute.")).toBeInTheDocument();
    await userEvent.click(screen.getByRole("button", { name: /try again/i }));
    expect(await screen.findByText("Area grows 9 times.")).toBeInTheDocument();
  });

  it("does not offer a retry when the AI key was rejected", async () => {
    mockApi({
      ...base,
      ...aiOn,
      "GET /api/v2/practice/p2/next": { body: choiceQuestion },
      "POST /api/v2/practice/p2/answer": { body: wrongAnswer },
      "POST /api/v2/ai/explain": { status: 503, body: { error: { code: "ai_key_rejected", message: "OpenRouter rejected the key." } } },
    });
    renderAt("/practice/p2");
    await userEvent.click(await screen.findByText("About 100 in²"));
    await userEvent.click(screen.getByRole("button", { name: /submit answer/i }));
    await userEvent.click(await screen.findByRole("button", { name: /explain my mistake with ai/i }));
    expect(await screen.findByText("The AI tutor isn't available right now.")).toBeInTheDocument();
    expect(screen.queryByRole("button", { name: /try again/i })).not.toBeInTheDocument();
  });

  it("explains why a question was chosen only on request, with the technical text nested", async () => {
    const calls = mockApi({
      ...base,
      "GET /api/v2/practice/p1/next": { body: choiceQuestion },
      "POST /api/v2/practice/p1/answer": {
        body: { ...wrongAnswer, interaction_id: 78, correct: true, hint_used: false, message: "Correct!", difficulty_next: "hard", difficulty_change: "up" },
      },
    });
    renderAt("/practice/p1");
    expect(await screen.findByText("Which could be the area of circle B?")).toBeInTheDocument();
    expect(screen.queryByText(choiceQuestion.selection!.how)).not.toBeInTheDocument();
    await userEvent.click(screen.getByRole("button", { name: /why this question/i }));
    expect(screen.getByText(choiceQuestion.selection!.how)).toBeInTheDocument();
    expect(screen.getByText(/No unused medium questions/)).toBeInTheDocument();
    expect(screen.queryByText(/Predicted success 61%/)).not.toBeInTheDocument();
    await userEvent.click(screen.getByRole("button", { name: "Details" }));
    expect(screen.getByText(/Predicted success 61%/)).toBeInTheDocument();
    await userEvent.click(screen.getByText("About 2,700 in²"));
    await userEvent.click(screen.getByRole("button", { name: /submit answer/i }));
    expect(await screen.findByText("Correct!")).toBeInTheDocument();
    expect(screen.getByText(/The next one is a little harder/)).toBeInTheDocument();
    expect(calls.find((c) => c.path === "/api/v2/practice/p1/answer")!.body).toEqual({ item_id: 178083, choice: "2", reveal: false });
  });

  it("stops early with the server's message and shows a summary with one next step", async () => {
    mockApi({
      ...base,
      "GET /api/v2/practice/p3/next": { body: choiceQuestion },
      "POST /api/v2/practice/p3/answer": {
        body: {
          ...wrongAnswer,
          correct: true,
          message: "Correct!",
          complete: true,
          early_stop: { reason: "mastered", message: "You've mastered this skill for now. Great work!" },
          summary: { accuracy: 0.8, correct: 4, answered: 5, skill_accuracy: 0.7, skill_attempts: 10, predicted_p: 0.8, mode: "guided", next: { action: "reassess", label: "Take the 5-question check", why: "You met the mastery rule." } },
        },
      },
    });
    renderAt("/practice/p3");
    await userEvent.click(await screen.findByText("About 2,700 in²"));
    await userEvent.click(screen.getByRole("button", { name: /submit answer/i }));
    expect(await screen.findByText("You've mastered this skill for now. Great work!")).toBeInTheDocument();
    await userEvent.click(screen.getByRole("button", { name: /see summary/i }));
    expect(screen.getByRole("heading", { name: "Practice complete" })).toBeInTheDocument();
    expect(screen.getAllByRole("button").filter(isPrimary).map((b) => b.textContent)).toEqual(["Take the 5-question check"]);
    expect(screen.queryByText(/model estimate/i)).not.toBeInTheDocument();
  });
});

