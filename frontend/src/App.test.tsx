/**
 * Screen-level tests: each page is rendered against a mocked API and checked for the
 * behaviours the product depends on (one clear next step, plain labels, details behind a
 * click, no answer leaks, working AI retry).
 */
import { render, screen, waitFor, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { MemoryRouter } from "react-router";
import { afterEach, describe, expect, it, vi } from "vitest";
import { AuthProvider } from "./auth/AuthContext";
import { AppRoutes } from "./App";
import { Markdown } from "./components/Markdown";
import { QuestionView } from "./components/QuestionView";
import { resetAiStatus } from "./components/AiTutor";
import { setAccessToken } from "./api/client";
import { loggedIn, mockApi } from "./test/mockApi";
import { choiceQuestion, diagnosis, geoInfo, home, numericQuestion, profile, skill, skillDetail, subjectInfo } from "./test/fixtures";

function renderAt(path: string) {
  return render(
    <MemoryRouter initialEntries={[path]}>
      <AuthProvider>
        <AppRoutes />
      </AuthProvider>
    </MemoryRouter>,
  );
}

afterEach(() => {
  vi.unstubAllGlobals();
  setAccessToken(null);
  resetAiStatus();
});

const aiOn = { "GET /api/v2/ai/status": { body: { enabled: true, model: "test-model", daily_limit: 40, used_today: 0, label: "AI-generated by a free language model.", key_ok: true } } };
const aiOff = { "GET /api/v2/ai/status": { body: { enabled: false, model: null, daily_limit: 40, used_today: 0, label: "" } } };
