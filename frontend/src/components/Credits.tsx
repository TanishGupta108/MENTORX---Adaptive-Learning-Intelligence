/** Data sources and licences. Live text comes from GET /subjects; the static text is the fallback
 * (and what the public landing page shows). */
import type { SubjectInfo } from "../api/tutor";

export const MAP_NOTICE = "Maps are simplified for practice and do not show official international boundaries.";

export const STATIC_CREDITS = [
  { code: "MATH", name: "Mathematics", text: "Mathematics questions: FoundationalASSIST (ASSISTments), CC BY-NC 4.0." },
  {
    code: "GEO",
    name: "Geography",
    text:
      "Geography practice data © Adaptive Learning group, Masaryk University (slepemapy.cz), Open Database License 1.0. " +
      "Papoušek, Pelánek & Stanislav (2016), Adaptive Geography Practice Data Set, Journal of Learning Analytics 3(2). " +
      "Map outlines: adaptive-learning/geography, MIT licence, © 2013 Vít Stanislav.",
  },
];

export function Credits({ subjects, showStatic = false }: { subjects?: SubjectInfo[] | null; showStatic?: boolean }) {
  const live = (subjects ?? []).filter((s) => s.attribution);
  const rows = live.length && !showStatic ? live.map((s) => ({ code: s.code, name: s.name, text: s.attribution, notice: s.notice })) : STATIC_CREDITS.map((c) => ({ ...c, notice: c.code === "GEO" ? MAP_NOTICE : null }));
  return (
    <dl className="space-y-4 text-sm">
      {rows.map((r) => (
        <div key={r.code}>
          <dt className="font-medium">{r.name}</dt>
          <dd className="mt-1 text-ink-muted">{r.text}</dd>
          {r.notice && <dd className="mt-1 text-xs text-ink-faint">{r.notice}</dd>}
        </div>
      ))}
      <div>
        <dt className="font-medium">Notes and AI help</dt>
        <dd className="mt-1 text-ink-muted">Notes and worked examples are written for MENTORX (AI-assisted, pending teacher review). AI tutor answers are generated by free language models and labelled as AI-generated.</dd>
      </div>
    </dl>
  );
}
