"""Paired comparison of the selected models of several experiments that share a test set.

Usage (from ml/):
    python scripts/compare.py --out reports/models/ablations.md \
        --group "ASSISTments 2009: difficulty features" \
            configs/assist2009.yaml configs/assist2009_no_item_difficulty.yaml \
            configs/assist2009_history_only.yaml \
        --group "EdNet: time features" configs/ednet.yaml configs/ednet_no_time.yaml

This adds no new model choices: it re-uses the already-selected models and the test
split they were evaluated on, and resamples students jointly so differences are paired.
The first config of each group is the reference.
"""

from __future__ import annotations

import argparse
import json
from datetime import UTC, datetime
from pathlib import Path

import joblib
import numpy as np

from mentorx_ml import metrics
from mentorx_ml.experiment import artifact_dir, experiment_name, load_config, prepare, report_dir


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--group",
        nargs="+",
        action="append",
        required=True,
        help="title followed by config paths; first config is the reference",
    )
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--reps", type=int, default=200)
    args = parser.parse_args()

    lines = [
        "# Ablation comparisons (paired, on test students)",
        "",
        "_Generated by `ml/scripts/compare.py`. Each group's experiments share the same data, split "
        "and test students; students are resampled jointly, so the Δ intervals are paired._",
        "",
    ]
    for title, *paths in args.group:
        configs = [load_config(Path(p)) for p in paths]
        preds, ys, students, labels = {}, None, None, {}
        for cfg in configs:
            sel = json.loads((report_dir(cfg) / "selection.json").read_text(encoding="utf-8"))
            prep = prepare(cfg)
            model = joblib.load(artifact_dir(cfg) / f"{sel['chosen']}.joblib")["model"]
            name = experiment_name(cfg)
            preds[name] = model.predict(prep.frames["test"], prep.X["test"])
            labels[name] = f"{name} ({sel['chosen']}, {len(prep.features)} features)"
            y = prep.y["test"]
            s = prep.frames["test"]["student_id"].to_numpy()
            if ys is None:
                ys, students = y, s
            elif not (np.array_equal(ys, y) and np.array_equal(students, s)):
                raise SystemExit(f"{name}: test set differs from the reference; can't pair.")
        ref = experiment_name(configs[0])
        ci = metrics.bootstrap_by_student(students, ys, preds, n_boot=args.reps, reference=ref)
        lines += [
            f"## {title}",
            "",
            f"Reference: `{ref}` · {len(ys):,} test answers, {len(set(students)):,} students",
            "",
            "| Experiment | Test AUC | Test log loss | Δ AUC vs reference (95% CI) | Δ log loss vs reference (95% CI) |",
            "|---|---:|---:|---|---|",
        ]
        for name, p in preds.items():
            m = metrics.compute(ys, p)
            if name == ref:
                lines.append(f"| {labels[name]} | {m['auc']:.4f} | {m['log_loss']:.4f} | — | — |")
                continue
            r = metrics.compute(ys, preds[ref])
            da, dl = ci[name]["delta_auc"], ci[name]["delta_log_loss"]
            lines.append(
                f"| {labels[name]} | {m['auc']:.4f} | {m['log_loss']:.4f} | "
                f"{m['auc'] - r['auc']:+.4f} ({da[0]:+.4f} to {da[1]:+.4f}) | "
                f"{m['log_loss'] - r['log_loss']:+.4f} ({dl[0]:+.4f} to {dl[1]:+.4f}) |"
            )
        lines.append("")
    lines.append(f"_Generated {datetime.now(UTC).isoformat(timespec='seconds')}._")
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
