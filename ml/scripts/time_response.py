"""How does the selected model's prediction change with time since the concept was last practised?

Usage (from ml/):  python scripts/time_response.py --config configs/ednet.yaml

Takes validation rows where the concept was practised before, sets
`log_secs_since_concept` to a fixed value for all of them (everything else unchanged),
and averages the predictions: a partial-dependence curve. MENTORX relies on this
curve going DOWN with time, because that decline is what schedules revision.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import joblib
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from mentorx_ml.experiment import artifact_dir, load_config, prepare, report_dir  # noqa: E402

POINTS = [
    ("1 minute", 60),
    ("10 minutes", 600),
    ("1 hour", 3600),
    ("1 day", 86400),
    ("3 days", 3 * 86400),
    ("1 week", 7 * 86400),
    ("2 weeks", 14 * 86400),
    ("1 month", 30 * 86400),
    ("3 months", 90 * 86400),
    ("6 months", 180 * 86400),
]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--rows", type=int, default=20000)
    args = parser.parse_args()
    cfg = load_config(args.config)
    excluded = cfg["features"].get("exclude", [])
    if not cfg["features"]["use_time"] or "log_secs_since_concept" in excluded:
        raise SystemExit("This experiment has no time features.")

    prep = prepare(cfg)
    sel = json.loads((report_dir(cfg) / "selection.json").read_text(encoding="utf-8"))
    model = joblib.load(artifact_dir(cfg) / f"{sel['chosen']}.joblib")["model"]
    X = prep.X["val"]
    X = X[X["is_first_concept"] == 0]
    X = X.sample(min(args.rows, len(X)), random_state=0)

    curve = []
    for label, secs in POINTS:
        Z = X.copy()
        Z["log_secs_since_concept"] = np.log1p(secs)
        curve.append(
            {"label": label, "seconds": secs, "mean_p": float(model.predict(None, Z).mean())}
        )

    out = report_dir(cfg)
    fig, ax = plt.subplots(figsize=(6.4, 3.4))
    ax.plot(
        [c["seconds"] for c in curve], [c["mean_p"] for c in curve], marker="o", color="#3b5bdb"
    )
    ax.set_xscale("log")
    ax.set_xticks([c["seconds"] for c in curve])
    ax.set_xticklabels([c["label"] for c in curve], rotation=40, ha="right", fontsize=8)
    ax.set_ylabel("mean predicted P(correct)")
    ax.set_title("Predicted accuracy vs time since last practice", loc="left")
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(out / "time_response.png", dpi=120)
    plt.close(fig)

    peak = max(curve, key=lambda c: c["mean_p"])
    last = curve[-1]
    lines = [
        f"# Time response: {cfg.get('name', cfg['dataset'])} ({sel['chosen']})",
        "",
        "_Generated by `ml/scripts/time_response.py`._",
        "",
        f"Partial dependence on `log_secs_since_concept`, averaged over {len(X):,} validation answers "
        "where the concept had been practised before (all other features unchanged).",
        "",
        "| Time since last practice | Mean predicted P(correct) |",
        "|---|---:|",
        *[f"| {c['label']} | {c['mean_p']:.3f} |" for c in curve],
        "",
        f"Peak {peak['mean_p']:.3f} at {peak['label']}; {last['mean_p']:.3f} after {last['label']} "
        f"({last['mean_p'] - peak['mean_p']:+.3f}).",
        "",
        "**Caveat:** this is observational data. Students who come back after a long gap may differ from "
        "those who don't, so the curve shows what the model learned, not a controlled forgetting experiment.",
        "",
        "![Time response](time_response.png)",
        "",
    ]
    (out / "time_response.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines[8:20]))


if __name__ == "__main__":
    main()
