"""Exploratory data analysis on a cleaned dataset. Writes figures, summary.json and report.md.

Usage (from ml/):  python scripts/eda.py --dataset assist2009

Every number in the report is computed here from the processed data; nothing is typed by hand.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from mentorx_ml import eda  # noqa: E402

ML_DIR = Path(__file__).resolve().parents[1]
INK, ACCENT, MUTED = "#1c1c1a", "#3b5bdb", "#8a8a84"

plt.rcParams.update(
    {
        "figure.dpi": 120,
        "axes.spines.top": False,
        "axes.spines.right": False,
        "axes.edgecolor": MUTED,
        "axes.labelcolor": INK,
        "xtick.color": INK,
        "ytick.color": INK,
        "font.size": 10,
    }
)


def _save(fig, path: Path) -> None:
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def plot_hist_log(values: pd.Series, xlabel: str, title: str, path: Path) -> None:
    fig, ax = plt.subplots(figsize=(6, 3.4))
    bins = np.logspace(0, np.log10(max(values.max(), 10)), 40)
    ax.hist(values, bins=bins, color=ACCENT)
    ax.set_xscale("log")
    ax.set_xlabel(xlabel)
    ax.set_ylabel("count")
    ax.set_title(title, loc="left")
    _save(fig, path)


def plot_learning_curve(curve: pd.DataFrame, path: Path) -> None:
    fig, ax1 = plt.subplots(figsize=(6.4, 3.6))
    ax1.fill_between(
        curve["opportunity"], curve["ci_low"], curve["ci_high"], color=ACCENT, alpha=0.2
    )
    ax1.plot(curve["opportunity"], curve["p_correct"], color=ACCENT, marker="o", ms=3)
    ax1.set_xticks(range(1, int(curve["opportunity"].max()) + 1, 2))
    ax1.set_xlabel("practice opportunity on the concept (1 = first attempt)")
    ax1.set_ylabel("P(correct)", color=ACCENT)
    ax1.set_ylim(0, 1)
    ax2 = ax1.twinx()
    ax2.bar(curve["opportunity"], curve["n"], color=MUTED, alpha=0.25, width=0.8)
    ax2.set_ylabel("interactions (bars)", color=MUTED)
    ax2.set_yscale("log")
    ax2.spines["right"].set_visible(True)
    ax1.set_zorder(ax2.get_zorder() + 1)
    ax1.patch.set_visible(False)
    ax1.set_title("Learning curve: accuracy by practice opportunity", loc="left")
    _save(fig, path)


def plot_conditional(cond: pd.DataFrame, path: Path) -> None:
    order = ["first attempt", "previous incorrect", "previous correct"]
    cond = cond.set_index("previous").loc[[o for o in order if o in set(cond["previous"])]]
    fig, ax = plt.subplots(figsize=(6.4, 3))
    err = np.vstack([cond["p_correct"] - cond["ci_low"], cond["ci_high"] - cond["p_correct"]])
    ax.barh(cond.index, cond["p_correct"], xerr=err, color=ACCENT, capsize=3)
    for i, p in enumerate(cond["p_correct"]):
        ax.text(p + 0.02, i, f"{p:.2f}", va="center", color=INK)
    ax.set_xlim(0, 1)
    ax.set_xlabel("P(correct) on the next attempt at the same concept")
    ax.set_title("Accuracy by previous outcome (same concept)", loc="left")
    _save(fig, path)


def plot_accuracy_hist(values: pd.Series, xlabel: str, title: str, path: Path) -> None:
    fig, ax = plt.subplots(figsize=(6, 3.2))
    ax.hist(values, bins=np.linspace(0, 1, 21), color=ACCENT)
    ax.set_xlabel(xlabel)
    ax.set_ylabel("count")
    ax.set_title(title, loc="left")
    _save(fig, path)


def plot_response_times(df: pd.DataFrame, path: Path) -> None:
    rt = df.dropna(subset=["response_ms"])
    rt = rt[rt["response_ms"] < rt["response_ms"].quantile(0.99)]
    fig, ax = plt.subplots(figsize=(6, 3.2))
    bins = np.logspace(
        np.log10(max(rt["response_ms"].min(), 100)), np.log10(rt["response_ms"].max()), 50
    )
    for value, label, color in ((1, "correct", ACCENT), (0, "incorrect", MUTED)):
        ax.hist(
            rt.loc[rt["correct"] == value, "response_ms"] / 1000,
            bins=bins / 1000,
            alpha=0.6,
            label=label,
            color=color,
        )
    ax.set_xscale("log")
    ax.set_xlabel("time to first response (seconds, log scale; top 1% removed)")
    ax.set_ylabel("interactions")
    ax.legend(frameon=False)
    ax.set_title("Response time by correctness", loc="left")
    _save(fig, path)


def _fmt(x: float, pct: bool = False) -> str:
    return f"{x:.1%}" if pct else f"{x:,.0f}"


def write_report(
    name: str, s: dict, curve, cond, rt, rapid: dict, out: Path, cleaning_md: str
) -> None:
    ips, ipc, ipi = (
        s["interactions_per_student"],
        s["interactions_per_concept"],
        s["interactions_per_item"],
    )
    c = cond.set_index("previous")["p_correct"]
    first, last = curve.iloc[0], curve.iloc[-1]
    rt_med = rt.set_index("correct")["median_ms"]
    lines = [
        f"# EDA report: {name}",
        "",
        "_Generated by `ml/scripts/eda.py` from the processed data. Do not edit by hand; re-run the script._",
        "",
        "## Cleaning",
        "",
        cleaning_md,
        "",
        "## Size",
        "",
        "| Measure | Value |",
        "|---|---:|",
        f"| Interactions | {_fmt(s['interactions'])} |",
        f"| Students | {_fmt(s['students'])} |",
        f"| Items (problems) | {_fmt(s['items'])} |",
        f"| Concepts (skill tags) | {_fmt(s['concepts'])} |",
        f"| Overall correct rate | {_fmt(s['correct_rate'], True)} |",
        f"| Majority-class accuracy (always predict 'correct') | {_fmt(max(s['correct_rate'], 1 - s['correct_rate']), True)} |",
        f"| Has clock timestamps | {'yes' if s['has_timestamps'] else 'no (order only)'} |",
        f"| Response time missing | {_fmt(s['response_ms_missing_rate'], True)} |",
        "",
        "## Distributions",
        "",
        "| Per | median | p10 | p90 | p99 | mean |",
        "|---|---:|---:|---:|---:|---:|",
        f"| Interactions per student | {ips['p50']:.0f} | {ips['p10']:.0f} | {ips['p90']:.0f} | {ips['p99']:.0f} | {ips['mean']:.1f} |",
        f"| Interactions per concept | {ipc['p50']:.0f} | {ipc['p10']:.0f} | {ipc['p90']:.0f} | {ipc['p99']:.0f} | {ipc['mean']:.1f} |",
        f"| Interactions per item | {ipi['p50']:.0f} | {ipi['p10']:.0f} | {ipi['p90']:.0f} | {ipi['p99']:.0f} | {ipi['mean']:.1f} |",
        "",
        f"- {s['students_with_lt_5_interactions']:,} students have fewer than 5 interactions (cold-start cases).",
        f"- {s['items_with_lt_5_interactions']:,} of {s['items']:,} items "
        f"({s['items_with_lt_5_interactions'] / s['items']:.0%}) have fewer than 5 interactions, "
        f"and the median item has only {ipi['p50']:.0f}. Raw per-item difficulty is therefore noisy: "
        "it must be smoothed towards the concept average (and fitted on training students only).",
        "",
        "![Interactions per student](students.png)",
        "",
        "![Interactions per concept](concepts.png)",
        "",
        "## Does past performance predict the next answer?",
        "",
        "| Previous outcome on the same concept | P(correct) | 95% CI | n |",
        "|---|---:|---|---:|",
    ]
    for _, row in cond.sort_values("p_correct").iterrows():
        lines.append(
            f"| {row['previous']} | {row['p_correct']:.3f} | {row['ci_low']:.3f}–{row['ci_high']:.3f} | {int(row['n']):,} |"
        )
    lines += [
        "",
        f"After a correct answer, the next answer on that concept is correct {c.get('previous correct', float('nan')):.1%} of the time, versus {c.get('previous incorrect', float('nan')):.1%} after an incorrect one. "
        "This gap is the signal knowledge-tracing models exploit.",
        "",
        "![Conditional accuracy](conditional.png)",
        "",
        "## Learning curve",
        "",
        f"P(correct) is {first['p_correct']:.3f} at the first opportunity (n = {int(first['n']):,}) and {last['p_correct']:.3f} at opportunity {int(last['opportunity'])} (n = {int(last['n']):,}).",
        "",
        "**Read with care: survivor bias.** In Skill Builder (mastery) assignments a student stops once they get 3 in a row right. "
        "Students still practising at high opportunity counts are disproportionately the ones who are struggling, so the pooled curve "
        "under-states how much individual students learn. A model must condition on each student's history rather than read the pooled curve.",
        "",
        "![Learning curve](learning_curve.png)",
        "",
        "## Students and items",
        "",
        "![Student accuracy](student_accuracy.png)",
        "",
        "![Item accuracy](item_accuracy.png)",
        "",
        "## Response time",
        "",
        f"Median time to first response: {rt_med.get('correct', float('nan')) / 1000:.1f} s for correct answers, {rt_med.get('incorrect', float('nan')) / 1000:.1f} s for incorrect ones.",
        "",
        f"Answers faster than {rapid['threshold_ms'] / 1000:.0f} s make up {rapid['share_fast']:.1%} of responses "
        f"(n = {rapid['n_fast']:,}) and are correct only {rapid['p_correct_fast']:.1%} of the time, versus "
        f"{rapid['p_correct_rest']:.1%} for slower answers. This supports MENTORX's rule that answers under 3 s don't "
        "count towards streaks (SRS FR-ENG-02), and suggests response time is a useful model feature.",
        "",
        "![Response times](response_time.png)",
        "",
    ]
    (out / "report.md").write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dataset", default="assist2009")
    args = parser.parse_args()

    df = pd.read_parquet(ML_DIR / "data" / "processed" / f"{args.dataset}.parquet")
    out = ML_DIR / "reports" / "eda" / args.dataset
    out.mkdir(parents=True, exist_ok=True)

    s = eda.summary(df)
    curve = eda.learning_curve(df)
    cond = eda.conditional_on_previous(df)
    rt = eda.response_time_by_correctness(df)
    rapid = eda.rapid_responses(df)

    plot_hist_log(
        df.groupby("student_id").size(),
        "interactions per student (log scale)",
        "How much each student practised",
        out / "students.png",
    )
    plot_hist_log(
        df.groupby("concept_id").size(),
        "interactions per concept (log scale)",
        "How much each concept was practised",
        out / "concepts.png",
    )
    plot_learning_curve(curve, out / "learning_curve.png")
    plot_conditional(cond, out / "conditional.png")
    plot_accuracy_hist(
        eda.entity_accuracy(df, "student_id"),
        "student correct rate",
        "Student accuracy (students with ≥ 10 interactions)",
        out / "student_accuracy.png",
    )
    plot_accuracy_hist(
        eda.entity_accuracy(df, "item_id"),
        "item correct rate",
        "Item accuracy (items with ≥ 10 interactions)",
        out / "item_accuracy.png",
    )
    plot_response_times(df, out / "response_time.png")

    payload = {
        "summary": s,
        "learning_curve": curve.to_dict(orient="records"),
        "conditional_on_previous": cond.to_dict(orient="records"),
        "response_time_by_correctness": rt.to_dict(orient="records"),
        "rapid_responses": rapid,
    }
    (out / "summary.json").write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    cleaning_md = (
        (out / "cleaning.md").read_text(encoding="utf-8")
        if (out / "cleaning.md").exists()
        else "_Run scripts/clean.py first._"
    )
    write_report(args.dataset, s, curve, cond, rt, rapid, out, cleaning_md.strip())
    print(f"Wrote {out / 'report.md'} and figures")


if __name__ == "__main__":
    main()
