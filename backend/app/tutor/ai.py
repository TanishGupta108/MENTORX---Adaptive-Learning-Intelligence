def admin_list(db: Session, limit: int = 100) -> list[dict]:
    rows = db.execute(
        select(AiExplanation, Item)
        .join(Item, Item.id == AiExplanation.item_id)
        .order_by(AiExplanation.created_at.desc())
        .limit(limit)
    ).all()
    return [
        {
            "id": r.id,
            "item_id": r.item_id,
            "question": plain_text(it.body_html)[:160],
            "kind": r.kind,
            "answer_sig": r.answer_sig.split(":")[0],
            "content": r.content,
            "model": r.model,
            "status": r.status,
            "latency_ms": r.latency_ms,
            "created_at": r.created_at,
        }
        for r, it in rows
    ]


