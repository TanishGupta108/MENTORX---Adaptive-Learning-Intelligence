"""NFR-MAINT-03: the SQLAlchemy models and the Alembic migrations must describe the same schema."""

from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected


def test_models_match_migrations(migrated_database):
    try:
        command.check(migrated_database)
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
        raise AssertionError(
            f"Models differ from migrations; run `alembic revision --autogenerate`:\n{exc}"
        ) from exc
